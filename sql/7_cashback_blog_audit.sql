-- Заказ с промокодом, скидками на товары и оплатой части суммы кэшбэком (до 50%).
drop function if exists public.create_order(jsonb, text, text, text);
create or replace function public.create_order(items jsonb, promo_code text, pay text, addr text default '', p_cashback_to_use integer default 0)
returns jsonb language plpgsql security definer set search_path to 'pg_catalog', 'public' as $function$
declare
  sub integer;
  lines jsonb;
  pct integer;
  tot integer;
  oid bigint;
  pr public.profiles%rowtype;
  code text;
  cb integer := greatest(coalesce(p_cashback_to_use, 0), 0);
begin
  if auth.uid() is null then
    raise exception 'login required';
  end if;

  select * into pr from public.profiles where id = auth.uid() for update;
  if not found then
    raise exception 'profile not found';
  end if;

  with l as (
    select p.id, p.kind, p.title, p.price as original_price,
      round(p.price * (100 - coalesce(p.discount_percent, 0)) / 100.0)::int as sale_price,
      coalesce(p.discount_percent, 0) as discount_percent,
      greatest(1, least(99, (i->>'qty')::int)) as q
    from jsonb_array_elements(items) i
    join public.products p on p.id = (i->>'id')::int and p.active and p.price > 0
  )
  select coalesce(sum(sale_price * q), 0),
    coalesce(jsonb_agg(jsonb_build_object(
      'id', id, 'title', trim(kind || ' ' || title), 'qty', q,
      'price', sale_price, 'original_price', original_price,
      'discount_percent', discount_percent
    )), '[]'::jsonb)
  into sub, lines
  from l;

  if sub = 0 then
    raise exception 'empty order';
  end if;

  code := upper(trim(coalesce(promo_code, '')));
  pct := public.check_promo(code);
  tot := round(sub * (100 - pct) / 100.0);

  if cb > floor(tot * 0.50) then
    raise exception 'cashback limit exceeded: maximum is 50 percent of order';
  end if;
  if cb > coalesce(pr.cashback_balance, 0) then
    raise exception 'insufficient cashback balance';
  end if;

  insert into public.orders(user_id, customer_name, phone, items, promo, discount, total, payment, address, cashback_used)
  values (auth.uid(), pr.name, pr.phone, lines, nullif(code, ''), pct, tot - cb, pay, left(coalesce(addr, ''), 500), cb)
  returning id into oid;

  if cb > 0 then
    update public.profiles set cashback_balance = cashback_balance - cb where id = auth.uid();
    insert into public.cashback_redemptions(order_id, user_id, amount) values (oid, auth.uid(), cb);
  end if;

  return jsonb_build_object('id', oid, 'total', tot - cb, 'subtotal_after_promo', tot, 'cashback_used', cb);
end;
$function$;

-- Начисление кэшбэка при статусе 'done' и отмена начисления при смене статуса обратно.
-- Уровни: Bronze 1% (по умолчанию), Silver 2% (от 5 выполненных заказов), Gold 3% (от 10).
create or replace function public.apply_order_cashback()
returns trigger language plpgsql security definer set search_path to 'pg_catalog', 'public' as $function$
declare
  v_amount bigint;
  v_percent numeric(5,2);
  v_override numeric(5,2);
  v_completed_count integer;
begin
  if new.user_id is null then
    return new;
  end if;

  if new.status = 'done' and old.status is distinct from 'done' then
    select cashback_percent_override into v_override from public.profiles where id = new.user_id for update;
    select count(*)::integer into v_completed_count from public.orders where user_id = new.user_id and status = 'done';
    v_percent := coalesce(v_override, case when v_completed_count >= 10 then 3.00 when v_completed_count >= 5 then 2.00 else 1.00 end);

    update public.profiles set cashback_percent = v_percent where id = new.user_id;

    insert into public.cashback_transactions(order_id, user_id, amount, cashback_percent)
    values (new.id, new.user_id, round(greatest(coalesce(new.total,0),0) * v_percent / 100.0)::bigint, v_percent)
    on conflict (order_id) do update set reversed_at = null
      where public.cashback_transactions.reversed_at is not null
    returning amount into v_amount;

    if v_amount is not null then
      update public.profiles set cashback_balance = cashback_balance + v_amount where id = new.user_id;
    end if;

  elsif old.status = 'done' and new.status is distinct from 'done' then
    update public.cashback_transactions set reversed_at = now()
     where order_id = new.id and user_id = new.user_id and reversed_at is null
    returning amount into v_amount;

    if v_amount is not null then
      update public.profiles set cashback_balance = greatest(0, cashback_balance - v_amount) where id = new.user_id;
    end if;

    select cashback_percent_override into v_override from public.profiles where id = new.user_id;
    select count(*)::integer into v_completed_count from public.orders where user_id = new.user_id and status = 'done';
    v_percent := coalesce(v_override, case when v_completed_count >= 10 then 3.00 when v_completed_count >= 5 then 2.00 else 1.00 end);

    update public.profiles set cashback_percent = v_percent where id = new.user_id;
  end if;

  return new;
end;
$function$;

-- Возврат кэшбэка, потраченного на заказ, если заказ отменён (и повторное списание при восстановлении).
create or replace function public.restore_order_cashback_redemption()
returns trigger language plpgsql security definer set search_path to 'pg_catalog', 'public' as $function$
declare
  v_amount integer;
  v_user_id uuid;
begin
  if new.status = 'canceled' and old.status is distinct from 'canceled' then
    update public.cashback_redemptions set reversed_at = now()
      where order_id = new.id and reversed_at is null
      returning amount, user_id into v_amount, v_user_id;
    if v_amount is not null then
      update public.profiles set cashback_balance = cashback_balance + v_amount where id = v_user_id;
    end if;

  elsif old.status = 'canceled' and new.status is distinct from 'canceled' then
    select amount, user_id into v_amount, v_user_id
      from public.cashback_redemptions
      where order_id = new.id and reversed_at is not null
      for update;
    if v_amount is not null then
      update public.profiles set cashback_balance = cashback_balance - v_amount
        where id = v_user_id and cashback_balance >= v_amount;
      if not found then
        raise exception 'insufficient cashback balance to reactivate this order';
      end if;
      update public.cashback_redemptions set reversed_at = null where order_id = new.id;
    end if;
  end if;
  return new;
end;
$function$;

-- Списание остатков при статусах paid/shipped/done и возврат при отмене.
create or replace function public.apply_order_inventory()
returns trigger language plpgsql security definer set search_path to 'pg_catalog', 'public' as $function$
declare
  line jsonb;
  product_id integer;
  quantity integer;
  current_state boolean := false;
begin
  if new.status in ('paid','shipped','done') and old.status not in ('paid','shipped','done') then
    select applied into current_state from public.inventory_order_state where order_id = new.id for update;
    if coalesce(current_state,false) = false then
      for line in select value from jsonb_array_elements(coalesce(new.items,'[]'::jsonb))
      loop
        product_id := nullif(line->>'id','')::integer;
        quantity := greatest(1, least(99, coalesce(nullif(line->>'qty','')::integer,1)));
        if product_id is not null then
          update public.products set stock = stock - quantity
           where id = product_id and stock is not null and stock >= quantity;
          if not found then
            if exists(select 1 from public.products where id=product_id and stock is not null) then
              raise exception 'Недостаточно остатка товара ID %', product_id;
            end if;
          end if;
        end if;
      end loop;
      insert into public.inventory_order_state(order_id,applied,updated_at) values(new.id,true,now())
      on conflict(order_id) do update set applied=true,updated_at=now();
    end if;
  elsif new.status = 'canceled' and old.status in ('paid','shipped','done') then
    select applied into current_state from public.inventory_order_state where order_id = new.id for update;
    if coalesce(current_state,false) then
      for line in select value from jsonb_array_elements(coalesce(new.items,'[]'::jsonb))
      loop
        product_id := nullif(line->>'id','')::integer;
        quantity := greatest(1, least(99, coalesce(nullif(line->>'qty','')::integer,1)));
        if product_id is not null then
          update public.products set stock=stock+quantity where id=product_id and stock is not null;
        end if;
      end loop;
      update public.inventory_order_state set applied=false,updated_at=now() where order_id=new.id;
    end if;
  end if;
  return new;
end;
$function$;

-- Журнал изменений заказов, товаров и промокодов.
create or replace function public.write_admin_audit_log()
returns trigger language plpgsql security definer set search_path to 'pg_catalog', 'public' as $function$
declare
  old_row jsonb;
  new_row jsonb;
  rid text;
begin
  if tg_op <> 'INSERT' then old_row := to_jsonb(old); end if;
  if tg_op <> 'DELETE' then new_row := to_jsonb(new); end if;
  rid := coalesce(new_row->>'id', new_row->>'code', old_row->>'id', old_row->>'code');
  insert into public.admin_audit_logs(actor_id,table_name,record_id,action,old_data,new_data)
  values(auth.uid(),tg_table_name,rid,tg_op,old_row,new_row);
  if tg_op = 'DELETE' then return old; end if;
  return new;
end;
$function$;

-- Ручные действия админа с кэшбэком.
create or replace function public.admin_adjust_cashback(p_user_id uuid, p_amount bigint, p_reason text)
returns bigint language plpgsql security definer set search_path to 'pg_catalog', 'public' as $function$
declare
  v_balance bigint;
begin
  if auth.uid() is null or not public.is_admin() then
    raise exception 'admin access required' using errcode = '42501';
  end if;
  if p_amount is null or p_amount = 0 then
    raise exception 'amount must not be zero';
  end if;
  if p_reason is null or length(btrim(p_reason)) < 3 or length(btrim(p_reason)) > 300 then
    raise exception 'reason must contain 3 to 300 characters';
  end if;

  update public.profiles set cashback_balance = cashback_balance + p_amount
   where id = p_user_id and cashback_balance + p_amount >= 0
   returning cashback_balance into v_balance;

  if not found then
    if not exists (select 1 from public.profiles where id = p_user_id) then
      raise exception 'client not found';
    end if;
    raise exception 'adjustment would make cashback balance negative';
  end if;

  insert into public.cashback_admin_adjustments(user_id, amount, reason, admin_id)
  values (p_user_id, p_amount, btrim(p_reason), auth.uid());

  return v_balance;
end;
$function$;

create or replace function public.admin_set_cashback_percent(p_user_id uuid, p_percent numeric)
returns void language plpgsql security definer set search_path to 'pg_catalog', 'public' as $function$
begin
  if auth.uid() is null or not public.is_admin() then
    raise exception 'admin access required' using errcode = '42501';
  end if;
  if p_percent is null or p_percent < 0 or p_percent > 100 then
    raise exception 'cashback percent must be between 0 and 100';
  end if;
  update public.profiles
     set cashback_percent_override = round(p_percent, 2), cashback_percent = round(p_percent, 2)
   where id = p_user_id;
  if not found then
    raise exception 'client not found';
  end if;
end;
$function$;

create or replace function public.admin_clear_cashback_override(p_user_id uuid)
returns void language plpgsql security definer set search_path to 'pg_catalog', 'public' as $function$
declare
  v_count integer;
  v_percent numeric(5,2);
begin
  if auth.uid() is null or not public.is_admin() then
    raise exception 'admin access required' using errcode = '42501';
  end if;
  if not exists (select 1 from public.profiles where id = p_user_id) then
    raise exception 'client not found';
  end if;
  select count(*)::integer into v_count from public.orders where user_id = p_user_id and status = 'done';
  v_percent := case when v_count >= 10 then 3.00 when v_count >= 5 then 2.00 else 1.00 end;
  update public.profiles set cashback_percent_override = null, cashback_percent = v_percent where id = p_user_id;
end;
$function$;

-- Уведомление о новом заказе в Telegram через Edge Function `super-handler`.
-- Нужны: расширение pg_net, секрет `order_webhook_secret` в Vault и сама Edge Function
-- (токен бота хранится в её секретах, в этом файле его нет).
-- Замените адрес проекта, если база создаётся заново.
create or replace function public.notify_telegram_new_order()
returns trigger language plpgsql security definer set search_path to 'public', 'extensions', 'vault' as $function$
declare
  webhook_secret text;
begin
  select decrypted_secret into webhook_secret from vault.decrypted_secrets where name = 'order_webhook_secret' limit 1;
  if webhook_secret is null then
    raise warning 'Telegram webhook secret is missing';
    return new;
  end if;
  perform net.http_post(
    url := 'https://wbxglomqselnmoobdmfw.supabase.co/functions/v1/super-handler',
    headers := jsonb_build_object('Content-Type', 'application/json', 'x-order-secret', webhook_secret),
    body := jsonb_build_object('record', to_jsonb(new))
  );
  return new;
end;
$function$;

